// ──────────────────────────────────────────────────────────────────────
// CONTEXT + HOOK
// ──────────────────────────────────────────────────────────────────────
type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, fallback?: string) => string;
};

const TContext = createContext<Ctx | null>(null);

const STORAGE_KEY = 'swift_locale';

function detectInitial(): Locale {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (saved && MESSAGES[saved]) return saved;
    const browser = (navigator.language || 'en').slice(0, 2).toLowerCase() as Locale;
    if (MESSAGES[browser]) return browser;
  } catch {}
  return 'en';
}

export function TranslatorProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en');

  // Initial detection only on mount (avoid SSR mismatch)
  useEffect(() => {
    setLocaleState(detectInitial());
  }, []);

  // RTL handling for Arabic
  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.lang = locale;
    }
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try { window.localStorage.setItem(STORAGE_KEY, l); } catch {}
  }, []);

  const t = useCallback((key: string, fallback?: string) => {
    return MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? fallback ?? key;
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <TContext.Provider value={value}>{children}</TContext.Provider>;
}

export function useT(): Ctx {
  const ctx = useContext(TContext);
  if (!ctx) {
    // Fallback so components don't crash if used outside provider
    return {
      locale: 'en',
      setLocale: () => {},
      t: (key, fallback) => MESSAGES.en[key] ?? fallback ?? key,
    };
  }
  return ctx;
}
